/**
 * The page setup (spec: tanstack-start-descriptors, nextjs): the files that
 * render the block map's pages, written for the site's binding, in place of
 * v7's page routes:
 *
 * - `src/cms.ts`: `createCMS` over the block map and the content module, and
 *   the content client each request reads (the binding's `contentClient`, so
 *   drafts work);
 * - `src/open-page.server.ts`: the page for a URL, resolved as v7 rendered
 *   it: every section, then v7's section loaders (`loadSections`, when the
 *   block map has them), with v7's matchers told the page (`matchPage`) and
 *   the sticky A/B cookie written (`commitSegmentCookie`) on TanStack Start;
 * - TanStack Start: `src/page.functions.ts`, the page's server function. It
 *   takes the page's path and passes the page's URL on, never the request's:
 *   on a client-side navigation the request is the server-function call
 *   (`/_serverFn/…`), and v7 matched and loaded the page being opened;
 *   `src/page-view.tsx` renders the sections through `src/views.ts`; the
 *   catch-all route `src/routes/$.tsx` (and v7's home route) load it;
 * - Next.js: the catch-all page `src/app/[[...slug]]/page.tsx` (or v7's own
 *   catch-all), which binds the draft, opens the page and renders it.
 *
 * A file that exists is kept and reported, except v7's own page routes
 * (`cmsRouteConfig`, `createDecoPage`, …), which are replaced, and v7's admin
 * routes (`/deco/invoke`, `/deco/meta`, `/deco/render`), which are deleted:
 * v8 serves neither, and git has the old files.
 */
import fs from "node:fs";
import path from "node:path";
import { listSources } from "./compat";
import { type Framework, siteFramework } from "./framework";
import type { Report } from "./report";
import { relativeSpecifier } from "./vendor";

/** v7's page-route helpers: a route file that imports one is v7's, and is replaced. */
const V7_PAGE =
  /\b(cmsRouteConfig|cmsHomeRouteConfig|DecoPageRenderer|loadCmsPage|loadCmsHomePage|withSiteGlobals|createDecoPage)\b/;
/** v7's admin endpoints: a route file that imports one is deleted. */
const V7_ADMIN =
  /\b(decoInvokeRoute\w*|decoMetaRoute\w*|decoRenderRoute\w*|createDecoRouteHandlers|createDecoPreviewPage)\b/;
const IMPORTS_DECO = /from\s+["']@decocms\/(tanstack|nextjs|start|blocks)[^"']*["']/;

interface Wiring {
  framework: Framework;
  loadSections: boolean;
  matchPage: boolean;
  random: boolean;
  device: boolean;
}

const HEADER = (what: string) => [
  "/**",
  ...what.split("\n").map((l) => ` * ${l}`),
  " * Generated by the deco-v7-to-v8-migration skill; it's your code now.",
  " */",
];

function cmsFile(w: Wiring): string {
  const binding =
    w.framework === "tanstack" ? "@decocms/tanstack/server" : "@decocms/nextjs/server";
  return [
    ...HEADER(
      "The CMS, created once at module scope (/next/content#create-the-cms), and the content client each\nrequest reads: the draft the binding accepted, or the release.",
    ),
    'import { createCMS } from "@decocms/blocks";',
    `import { contentClient } from "${binding}";`,
    'import blocks from "../.deco";',
    'import content from "../.deco/blocks.gen";',
    "",
    "export const cms = createCMS({ blocks, content });",
    "",
    w.framework === "tanstack"
      ? "/** The client for this request: the draft createDecoWorker accepted, or the release. */\nexport const client = async (request: Request) => contentClient(cms, request);"
      : "/** The client for this request: the draft bindDraft bound (the catch-all page), or the release. */\nexport const client = async () => contentClient(cms);",
    "",
  ].join("\n");
}

/** The part of openPage both frameworks share: list, match, resolve every section, run the loaders. */
function resolveBody(w: Wiring, request: string): string[] {
  return [
    '  const [pages, pagesError] = await c.list<StoredPage>("page");',
    "  if (pagesError) throw pagesError;",
    '  const [redirects, redirectsError] = await c.list<Redirect>("redirect");',
    "  if (redirectsError) throw redirectsError;",
    "",
    "  const match = matchRoute(url, { routes: pages, redirects });",
    ...(w.framework === "tanstack"
      ? [
          '  if (match.kind === "not-found") throw notFound();',
          '  if (match.kind === "redirect") throw redirect({ href: match.location, statusCode: match.status });',
        ]
      : [
          '  if (match.kind === "not-found") notFound();',
          '  if (match.kind === "redirect") {',
          "    if (match.status === 301 || match.status === 308) permanentRedirect(match.location);",
          "    redirect(match.location);",
          "  }",
        ]),
    "",
    "  const page = match.entry;",
    "  // Variants of the whole list are one multivariate block: it resolves to the chosen list.",
    "  const saved = Array.isArray(page.sections) ? page.sections : page.sections ? [page.sections] : [];",
    "  const resolved = await Promise.all(",
    "    saved.map(async (block) => {",
    "      const [value, error] = await c.resolve<BlockDescriptor | BlockDescriptor[] | undefined>(block);",
    "      if (error) console.error(error); // a failed section renders nothing",
    "      return value ?? [];",
    "    }),",
    "  );",
    ...(w.loadSections
      ? [
          "  // v7's section loaders, as v7 ran them once the page resolved, at the page's URL.",
          `  const { sections, degraded } = await loadSections(resolved.flat(), ${request}, url);`,
        ]
      : ["  const sections = resolved.flat();"]),
    "",
    "  const [seo, seoError] = await c.resolve<unknown>(page.seo);",
    "  if (seoError) throw seoError;",
  ];
}

function openPageTanstack(w: Wiring): string {
  const deco = [
    "type BlockDescriptor",
    ...(w.loadSections ? ["loadSections"] : []),
    ...(w.matchPage ? ["matchPage"] : []),
  ];
  const compat = [
    ...(w.random ? ["commitSegmentCookie"] : []),
    ...(w.device ? ["requestDevice"] : []),
  ];
  return [
    ...HEADER(
      "Finds the page for a URL and resolves it the way v7 rendered it: every section, then v7's\nsection loaders (/next/tanstack-start-descriptors#3-match-the-url-to-a-page).",
    ),
    'import { matchRoute, type Redirect, type Route } from "@decocms/blocks";',
    ...(compat.length > 0
      ? [`import { ${compat.join(", ")} } from "@decocms/compat-v7/tanstack/server";`]
      : []),
    ...(w.loadSections ? ['import { DEGRADED_HEADER } from "@decocms/tanstack/server";'] : []),
    'import { notFound, redirect } from "@tanstack/react-router";',
    ...(w.loadSections
      ? ['import { setResponseHeader } from "@tanstack/react-start/server";']
      : []),
    `import { ${deco.join(", ")} } from "../.deco";`,
    'import { client } from "./cms";',
    "",
    "/** A page as saved: its sections and SEO are still blocks. */",
    "interface StoredPage extends Route {",
    "  sections?: unknown;",
    "  seo?: unknown;",
    "}",
    "",
    ...SEO_FIELDS,
    "",
    "/**",
    " * Opens the page at `href` (a path on this site, with its query) for `request`. Every read uses the",
    " * page's URL, never the request's: on a client-side navigation the request is the server-function",
    " * call (/_serverFn/…), and v7 matched and loaded the page being opened.",
    " */",
    "export async function openPage(href: string, request: Request) {",
    "  const url = new URL(href, request.url);",
    "  if (url.origin !== new URL(request.url).origin) throw notFound();",
    ...(w.matchPage
      ? [
          "  // v7's matchers read this page, not the server-function call.",
          "  matchPage(url, request);",
        ]
      : []),
    "  const c = await client(request);",
    ...resolveBody(w, "request"),
    ...(w.loadSections
      ? [
          "  // A section whose loader failed kept its saved props: v7 sent this header, and the worker never",
          "  // caches the page.",
          '  if (degraded.length > 0) setResponseHeader(DEGRADED_HEADER, "1");',
        ]
      : []),
    ...(w.random
      ? [
          "  // The sticky A/B groups the matchers drew (deco_segment, latest 7.x).",
          "  commitSegmentCookie(request);",
        ]
      : []),
    `  return { name: page.name, seo: seoFields(seo), sections${w.device ? ", device: requestDevice(request)" : ""} };`,
    "}",
    "",
  ].join("\n");
}

const PAGE_FUNCTIONS = [
  ...HEADER(
    "The page loader as a server function (/next/tanstack-start-descriptors#4-expose-it-through-a-server-function):\na plain call while the server renders, a fetch from the browser on a client-side navigation.",
  ),
  'import { createServerFn } from "@tanstack/react-start";',
  'import { getRequest } from "@tanstack/react-start/server";',
  'import { openPage } from "./open-page.server";',
  "",
  "/** A path on this site: `//host/x` is a protocol-relative URL that would open another origin. */",
  "function localPath(data: { href: string }): { href: string } {",
  "  const href = data?.href;",
  '  if (typeof href !== "string" || !href.startsWith("/") || href.startsWith("//") || href.startsWith("/\\\\")) {',
  '    throw new Error("not a local path");',
  "  }",
  "  return { href };",
  "}",
  "",
  "/** Opens the page at `href`: the page's path and query, which openPage reads instead of /_serverFn's. */",
  'export const loadPage = createServerFn({ method: "GET" })',
  "  .inputValidator(localPath)",
  "  .handler(({ data }) => openPage(data.href, getRequest()));",
  "",
].join("\n");

/** Shared by both frameworks' views: the head and the sections. */
function pageViewTanstack(w: Wiring): string {
  return [
    ...HEADER(
      "Renders an opened page: each section through the view registry (src/views.ts), by its v7 type\nname, with the page's SEO in the head.",
    ),
    ...(w.device
      ? ['import { type Device, DeviceProvider } from "@decocms/compat-v7/tanstack";']
      : []),
    'import type { BlockDescriptor } from "../.deco";',
    'import { views } from "./views";',
    "",
    "export interface PageData {",
    "  sections: BlockDescriptor[];",
    "  seo: { title?: string; description?: string };",
    ...(w.device ? ["  device: Device;"] : []),
    "}",
    "",
    "/** The page's title and description, for a route's `head`. */",
    "export function pageHead(page: PageData | undefined) {",
    "  const { title, description } = page?.seo ?? {};",
    "  return {",
    "    meta: [",
    "      ...(title ? [{ title }] : []),",
    '      ...(description ? [{ name: "description", content: description }] : []),',
    "    ],",
    "  };",
    "}",
    "",
    "export function PageView({ page }: { page: PageData }) {",
    "  const sections = page.sections.map((section, index) => {",
    "    const View = views[section.component]?.default;",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source with a template literal
    "    return View ? <View key={`${section.component}-${index}`} {...section.props} /> : null;",
    "  });",
    w.device
      ? "  return <DeviceProvider value={page.device}>{sections}</DeviceProvider>;"
      : "  return <>{sections}</>;",
    "}",
    "",
  ].join("\n");
}

const SEO_FIELDS = [
  "/** v7's SEO block returned its fields, or a section descriptor carrying them. */",
  "function seoFields(seo: unknown): { title?: string; description?: string } {",
  '  const fields = seo && typeof seo === "object" && "props" in seo ? (seo as { props: unknown }).props : seo;',
  '  if (!fields || typeof fields !== "object") return {};',
  "  const { title, description } = fields as Record<string, unknown>;",
  "  return {",
  '    title: typeof title === "string" ? title : undefined,',
  '    description: typeof description === "string" ? description : undefined,',
  "  };",
  "}",
];

function routeTanstack(routePath: "/" | "/$", fromRoutes: string): string {
  return [
    'import { createFileRoute } from "@tanstack/react-router";',
    `import { PageView, pageHead } from "${fromRoutes}/page-view";`,
    `import { loadPage } from "${fromRoutes}/page.functions";`,
    "",
    "// A CMS page, found by its URL (src/open-page.server.ts). Generated by the deco-v7-to-v8-migration skill.",
    `export const Route = createFileRoute("${routePath}")({`,
    "  loader: ({ location }) => loadPage({ data: { href: location.pathname + location.searchStr } }),",
    "  head: ({ loaderData }) => pageHead(loaderData),",
    "  component: CmsPage,",
    "});",
    "",
    "function CmsPage() {",
    "  return <PageView page={Route.useLoaderData()} />;",
    "}",
    "",
  ].join("\n");
}

function openPageNext(w: Wiring): string {
  const deco = ["type BlockDescriptor", ...(w.loadSections ? ["loadSections"] : [])];
  return [
    ...HEADER(
      "Finds the page for a URL and resolves it the way v7 rendered it: every section, then v7's\nsection loaders (/next/nextjs#4-match-the-url-to-a-page). React's cache shares one result between\ngenerateMetadata and the page.",
    ),
    'import { matchRoute, type Redirect, type Route } from "@decocms/blocks";',
    ...(w.device ? ['import { requestDevice } from "@decocms/compat-v7/nextjs/server";'] : []),
    'import { headers } from "next/headers";',
    'import { notFound, permanentRedirect, redirect } from "next/navigation";',
    'import { cache } from "react";',
    `import { ${deco.join(", ")} } from "../.deco";`,
    'import { client } from "./cms";',
    "",
    "/** A page as saved: its sections and SEO are still blocks. */",
    "interface StoredPage extends Route {",
    "  sections?: unknown;",
    "  seo?: unknown;",
    "}",
    "",
    "type SearchParams = Record<string, string | string[] | undefined>;",
    "",
    "/** The page's path and query, from the catch-all's segments and search params. */",
    "export function hrefFor(segments: string[] = [], searchParams: SearchParams = {}): string {",
    "  const query = new URLSearchParams();",
    "  for (const [key, value] of Object.entries(searchParams)) {",
    "    for (const v of Array.isArray(value) ? value : value === undefined ? [] : [value]) query.append(key, v);",
    "  }",
    "  const search = query.toString();",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source with a template literal
    '  return `/${segments.map(encodeURIComponent).join("/")}${search ? `?${search}` : ""}`;',
    "}",
    "",
    ...SEO_FIELDS,
    "",
    "/** Opens the page at `href` (a path on this site, with its query). */",
    "export const openPage = cache(async (href: string) => {",
    "  const incoming = await headers();",
    '  const host = incoming.get("x-forwarded-host") ?? incoming.get("host") ?? "localhost";',
    '  const protocol = incoming.get("x-forwarded-proto") ?? "https";',
    // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source with a template literal
    "  const url = new URL(href, `${protocol}://${host}`);",
    ...(w.loadSections
      ? ["  const request = new Request(url, { headers: new Headers(incoming) });"]
      : []),
    "  const c = await client();",
    ...resolveBody(w, "request"),
    `  return { name: page.name, seo: seoFields(seo), sections${w.loadSections ? ", degraded" : ""}${w.device ? ", device: await requestDevice()" : ""} };`,
    "});",
    "",
  ].join("\n");
}

function pageNext(w: Wiring, file: string, root: string, param: string): string {
  const from = (rel: string) => relativeSpecifier(file, path.join(root, "src", rel));
  return [
    ...HEADER(
      "Every CMS page: binds the request's draft, opens the page for its URL and renders each section\nthrough the view registry (src/views.ts), by its v7 type name (/next/nextjs#5-render-the-catch-all-route).",
    ),
    ...(w.device ? ['import { DeviceProvider } from "@decocms/compat-v7/nextjs";'] : []),
    ...(w.random ? ['import { SegmentCookie } from "@decocms/compat-v7/nextjs/server";'] : []),
    'import { bindDraft } from "@decocms/nextjs/server";',
    'import type { Metadata } from "next";',
    `import { cms } from "${from("cms.ts")}";`,
    `import { hrefFor, openPage } from "${from("open-page.server.ts")}";`,
    `import { views } from "${from("views.ts")}";`,
    "",
    "type Props = {",
    `  params: Promise<{ ${param}?: string[] }>;`,
    "  searchParams: Promise<Record<string, string | string[] | undefined>>;",
    "};",
    "",
    "async function pageFor({ params, searchParams }: Props) {",
    "  const query = await searchParams;",
    "  await bindDraft(cms, { searchParams: query });",
    `  return openPage(hrefFor((await params).${param}, query));`,
    "}",
    "",
    "export async function generateMetadata(props: Props): Promise<Metadata> {",
    "  const { title, description } = (await pageFor(props)).seo;",
    "  return { title, description };",
    "}",
    "",
    "export default async function Page(props: Props) {",
    "  const page = await pageFor(props);",
    "  const sections = page.sections.map((section, index) => {",
    "    const View = views[section.component]?.default;",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source with a template literal
    "    return View ? <View key={`${section.component}-${index}`} {...section.props} /> : null;",
    "  });",
    "  return (",
    "    <>",
    w.device
      ? "      <DeviceProvider value={page.device}>{sections}</DeviceProvider>"
      : "      {sections}",
    ...(w.random
      ? [
          "      {/* The sticky A/B groups the matchers drew (deco_segment, latest 7.x). */}",
          "      <SegmentCookie />",
        ]
      : []),
    "    </>",
    "  );",
    "}",
    "",
  ].join("\n");
}

/** The site's app directory on Next.js: `src/app`, else `app`, else a new `src/app`. */
function appDir(root: string): string {
  for (const dir of [path.join(root, "src", "app"), path.join(root, "app")]) {
    if (fs.existsSync(dir)) return dir;
  }
  return path.join(root, "src", "app");
}

/** A catch-all page directly in the app directory or one route group: `[[...x]]` or `[...x]`. */
function findCatchAll(dir: string): { file: string; param: string } | undefined {
  if (!fs.existsSync(dir)) return undefined;
  const candidates = [dir];
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    if (d.isDirectory() && /^\(.+\)$/.test(d.name)) candidates.push(path.join(dir, d.name));
  }
  for (const base of candidates) {
    for (const d of fs.readdirSync(base, { withFileTypes: true })) {
      const param = /^\[\[?\.\.\.([A-Za-z_$][\w$]*)\]\]?$/.exec(d.name)?.[1];
      if (!d.isDirectory() || !param) continue;
      for (const name of ["page.tsx", "page.ts", "page.jsx"]) {
        const file = path.join(base, d.name, name);
        if (fs.existsSync(file)) return { file, param };
      }
    }
  }
  return undefined;
}

/** Writes the page setup for the site's binding. */
export function writeScaffold(root: string, report: Report): void {
  const framework = siteFramework(root);
  if (!framework) return;
  const mapFile = path.join(root, ".deco", "index.ts");
  const map = fs.existsSync(mapFile) ? fs.readFileSync(mapFile, "utf8") : "";
  const rel = (file: string) => path.relative(root, file).split(path.sep).join("/");
  if (
    !/export interface BlockDescriptor/.test(map) ||
    !fs.existsSync(path.join(root, "src", "views.ts"))
  ) {
    report.manual.push({
      step: "scaffold",
      subject: "page setup",
      message: `the script didn't write the block map or src/views.ts this run, so it wrote no page setup: create src/cms.ts, the page loader and the catch-all route (${framework === "tanstack" ? "/next/tanstack-start-descriptors" : "/next/nextjs"})`,
    });
    return;
  }
  const sources = listSources(path.join(root, "src"));
  const device = sources.some((f) => /\buseDevice\s*\(/.test(fs.readFileSync(f, "utf8")));
  const w: Wiring = {
    framework,
    loadSections: /export function loadSections\b/.test(map),
    matchPage: /export function matchPage\b/.test(map),
    random: /matchers\.random\(/.test(map),
    device,
  };

  const written: string[] = [];
  const replaced: string[] = [];
  const kept: string[] = [];
  const write = (file: string, text: string, replaceV7 = false) => {
    if (fs.existsSync(file)) {
      const old = fs.readFileSync(file, "utf8");
      if (!(replaceV7 && IMPORTS_DECO.test(old) && V7_PAGE.test(old))) {
        kept.push(rel(file));
        return;
      }
      replaced.push(rel(file));
    } else {
      written.push(rel(file));
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  };
  const deleted: string[] = [];
  const dropAdmin = (dir: string) => {
    for (const file of listSources(dir)) {
      const text = fs.readFileSync(file, "utf8");
      if (IMPORTS_DECO.test(text) && V7_ADMIN.test(text) && !V7_PAGE.test(text)) {
        fs.rmSync(file);
        deleted.push(rel(file));
      }
    }
  };

  const src = (f: string) => path.join(root, "src", f);
  write(src("cms.ts"), cmsFile(w));
  if (framework === "tanstack") {
    write(src("open-page.server.ts"), openPageTanstack(w));
    write(src("page.functions.ts"), PAGE_FUNCTIONS);
    write(src("page-view.tsx"), pageViewTanstack(w));
    const routes = src("routes");
    write(path.join(routes, "$.tsx"), routeTanstack("/$", ".."), true);
    if (fs.existsSync(path.join(routes, "index.tsx"))) {
      write(path.join(routes, "index.tsx"), routeTanstack("/", ".."), true);
    }
    dropAdmin(routes);
  } else {
    write(src("open-page.server.ts"), openPageNext(w));
    const dir = appDir(root);
    const existing = findCatchAll(dir);
    const file = existing?.file ?? path.join(dir, "[[...slug]]", "page.tsx");
    write(file, pageNext(w, file, root, existing?.param ?? "slug"), true);
    dropAdmin(dir);
  }

  if (written.length + replaced.length > 0) {
    report.done.push({
      step: "scaffold",
      subject: "page setup",
      message: `${[...written, ...replaced].join(", ")}: the CMS, the page loader${framework === "tanstack" ? " (a server function that passes the page's URL, not /_serverFn's)" : ""} and the catch-all route, rendering through src/views.ts${w.loadSections ? ", running v7's section loaders" : ""}${w.random ? ", writing the sticky A/B cookie" : ""}${w.device ? ", seeding useDevice with the server's device" : ""}`,
    });
  }
  if (replaced.length > 0) {
    report.manual.push({
      step: "scaffold",
      subject: replaced.join(", "),
      message:
        "v7's page routes, replaced by the v8 page route: carry over what the site added to them (a not-found component, route options such as ignored search params or pending times, globals rendered around the page) from git",
    });
  }
  if (deleted.length > 0) {
    report.done.push({
      step: "scaffold",
      subject: deleted.join(", "),
      message:
        "v7's admin routes (/deco/invoke, /deco/meta, /deco/render): deleted, v8 serves none of them",
    });
  }
  if (kept.length > 0) {
    report.manual.push({
      step: "scaffold",
      subject: kept.join(", "),
      message: `already existed, so they were kept: check that they do what the generated page setup would (${framework === "tanstack" ? "/next/tanstack-start-descriptors" : "/next/nextjs"}): open the page at its own URL, run loadSections, and render through src/views.ts`,
    });
  }
  if (framework === "tanstack" && (replaced.length > 0 || deleted.length > 0)) {
    report.manual.push({
      step: "scaffold",
      subject: "src/routeTree.gen.ts",
      message:
        "regenerate it (the router plugin does on vite dev or build) after the route changes",
    });
  }
}
