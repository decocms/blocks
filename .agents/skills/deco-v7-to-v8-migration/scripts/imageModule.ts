/**
 * v7's image URLs on a TanStack Start site, written for it: `src/imageUrl.ts`
 * with the `createImageUrl` that gives the URLs v7's `Image` gave (the
 * release's rules, or the site's own copy of v7's image helper with what the
 * site registers on it), and `createDecoRouter`'s `Wrap` giving it to every
 * `Image`, `Picture` and `Source` through `ImageUrlProvider`.
 */
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { applyEdits, type Edit, importInsertion, listSources, parse } from "./compat";
import {
  copyDecoCdnOptions,
  DEFAULT_DOMAIN,
  type ImageCopy,
  type ImageCopyRules,
} from "./imageCopy";
import type { Report } from "./report";

/** The rules of the `Image` a 7.x release shipped (see `v7ImageUrl` in ./imports.ts); latest 7.x when unknown. */
export function releaseRules(version: string | undefined): ImageCopyRules {
  const [major, minor, patch] = (version ?? "").split(".").map(Number);
  const at = (m: number, p: number) => major === 7 && (minor > m || (minor === m && patch >= p));
  const base = { vtex: true, shopify: true };
  if (major !== 7 || Number.isNaN(minor)) {
    return {
      ...base,
      domain: DEFAULT_DOMAIN,
      stripAssetHosts: "leading",
      decoims: "cloudflare",
      nuvemshop: true,
    };
  }
  if (!at(71, 0)) {
    return {
      ...base,
      domain: "decoims.com",
      stripAssetHosts: "anywhere",
      decoims: "none",
      nuvemshop: false,
    };
  }
  if (!at(71, 4)) {
    return {
      ...base,
      domain: DEFAULT_DOMAIN,
      stripAssetHosts: "anywhere",
      decoims: "none",
      nuvemshop: false,
    };
  }
  if (!at(71, 5)) {
    return {
      ...base,
      domain: DEFAULT_DOMAIN,
      stripAssetHosts: "leading",
      decoims: "always",
      nuvemshop: false,
    };
  }
  return {
    ...base,
    domain: DEFAULT_DOMAIN,
    stripAssetHosts: "leading",
    decoims: "cloudflare",
    nuvemshop: at(77, 1),
  };
}

export interface ImageModule {
  /** The module's text, or undefined when the script can't write it (`reason`). */
  text?: string;
  reason?: string;
  /** Whether v7 had a Nuvemshop rule no package covers. */
  nuvemshop: boolean;
}

/** `src/imageUrl.ts` for the site: from its readable copy of v7's helper, else its release. */
export function imageModule(
  version: string | undefined,
  images: { copies: ImageCopy[]; registered: { domain?: string | null; quality?: string | null } },
): ImageModule {
  const copy = images.copies.find((c) => c.rules);
  if (images.copies.length > 0 && !copy) {
    return {
      reason: `the site's copy of v7's image helper (${images.copies[0].file}) was edited past what the script reads`,
      nuvemshop: false,
    };
  }
  const { registered } = images;
  if (registered.domain === null || registered.quality === null) {
    return {
      reason:
        "the site passes registerImageCdnDomain or registerImageQuality something other than one string literal",
      nuvemshop: false,
    };
  }
  const rules = copy?.rules ?? releaseRules(version);
  const providers = [
    rules.vtex ? "vtexCatalog()" : "",
    rules.shopify ? "shopifyCdn()" : "",
    `decoCdn({ ${copyDecoCdnOptions(rules, registered)} })`,
  ].filter(Boolean);
  const from = copy
    ? `the site's copy of v7's image helper (${copy.file}), whose rules win over its release's`
    : version
      ? `v7 ${version}'s Image`
      : "the latest 7.x Image";
  const set = [
    registered.domain ? `registerImageCdnDomain("${registered.domain}")` : "",
    registered.quality ? `registerImageQuality("${registered.quality}")` : "",
  ].filter(Boolean);
  const lines = [
    'import { createImageUrl, decoCdn } from "@decocms/blocks/image";',
    ...(rules.shopify ? ['import { shopifyCdn } from "@decocms/apps-shopify/image";'] : []),
    ...(rules.vtex ? ['import { vtexCatalog } from "@decocms/apps-vtex/image";'] : []),
    "",
    "/**",
    ` * The site's image URLs, byte for byte those of ${from}${set.length > 0 ? `, with the site's ${set.join(" and ")}` : ""}:`,
    ...(rules.vtex || rules.shopify
      ? [
          " * VTEX catalog and Shopify images resized on their platforms' own CDNs (v7 did both on every site),",
        ]
      : []),
    " * every other source through the Deco image CDN. Given to every Image, Picture and Source by the",
    " * ImageUrlProvider in createDecoRouter's Wrap. Generated by the deco-v7-to-v8-migration skill.",
    " */",
    "export const imageUrl = createImageUrl({",
    `  providers: [${providers.join(", ")}],`,
    "});",
    "",
  ];
  return { text: lines.join("\n"), nuvemshop: rules.nuvemshop };
}

const IMAGE_URL_FILES = ["imageUrl.ts", "imageUrl.tsx"];

/** Writes `src/imageUrl.ts` (kept when it exists) and wires `ImageUrlProvider` into `createDecoRouter`. */
export function writeImageUrl(
  root: string,
  report: Report,
  plan: ImageModule,
  /** The note when there's no module to write. */
  fallback: string,
): void {
  const existing = IMAGE_URL_FILES.find((f) => fs.existsSync(path.join(root, "src", f)));
  const file = path.join(root, "src", existing ?? "imageUrl.ts");
  if (existing) {
    report.manual.push({
      step: "imports",
      subject: `src/${existing}`,
      message: "already exists, so it was kept: it must export imageUrl, v7's image URLs",
    });
  } else if (plan.text) {
    fs.writeFileSync(file, plan.text);
    report.done.push({
      step: "imports",
      subject: "src/imageUrl.ts",
      message: "imageUrl: v7's image URLs (createImageUrl over the platforms' helpers and decoCdn)",
    });
  } else {
    report.manual.push({ step: "imports", subject: "Image, Picture, Source", message: fallback });
    return;
  }
  if (plan.nuvemshop && !existing) {
    report.manual.push({
      step: "imports",
      subject: "src/imageUrl.ts",
      message:
        "v7 also gave Nuvemshop product images (*.mitiendanube.com) the CDN's fixed sizes, which no @decocms/apps-* package covers: a store with such images lists its own provider before decoCdn (reference/framework-code.md)",
    });
  }
  wireImageUrlProvider(root, file, report);
}

/** `<ImageUrlProvider value={imageUrl}>` around every page, through `createDecoRouter`'s `Wrap`. */
function wireImageUrlProvider(root: string, imageFile: string, report: Report): void {
  const wired: string[] = [];
  const left: string[] = [];
  for (const file of listSources(path.join(root, "src"))) {
    const text = fs.readFileSync(file, "utf8");
    if (!text.includes("createDecoRouter(")) continue;
    const rel = path.relative(root, file).split(path.sep).join("/");
    if (text.includes("ImageUrlProvider")) continue;
    const source = parse(file, text);
    const edits: Edit[] = [];
    let bad = false;
    const visit = (node: ts.Node) => {
      if (
        ts.isCallExpression(node) &&
        ts.isIdentifier(node.expression) &&
        node.expression.text === "createDecoRouter"
      ) {
        const edit = file.endsWith(".tsx") ? wrapEdit(source, node) : undefined;
        if (edit) edits.push(edit);
        else bad = true;
      }
      ts.forEachChild(node, visit);
    };
    visit(source);
    if (bad || edits.length === 0 || /\bimageUrl\b/.test(text)) {
      left.push(rel);
      continue;
    }
    let spec = path.relative(path.dirname(file), imageFile).split(path.sep).join("/");
    spec = spec.replace(/\.tsx?$/, "");
    if (!spec.startsWith(".")) spec = `./${spec}`;
    const at = importInsertion(source);
    const imports = [
      'import { ImageUrlProvider } from "@decocms/tanstack/react";',
      `import { imageUrl } from "${spec}";`,
    ].join("\n");
    edits.push({ start: at, end: at, text: at === 0 ? `${imports}\n` : `\n${imports}` });
    fs.writeFileSync(file, applyEdits(text, edits));
    wired.push(rel);
  }
  if (wired.length > 0) {
    report.done.push({
      step: "imports",
      subject: wired.join(", "),
      message:
        "createDecoRouter's Wrap gives every Image, Picture and Source the site's imageUrl (ImageUrlProvider from @decocms/tanstack/react)",
    });
  }
  if (wired.length === 0 || left.length > 0) {
    report.manual.push({
      step: "imports",
      subject: left.length > 0 ? left.join(", ") : "ImageUrlProvider",
      message:
        "wrap every page in <ImageUrlProvider value={imageUrl}> (@decocms/tanstack/react, imageUrl from src/imageUrl.ts) through createDecoRouter's Wrap option: without it every source goes through the Deco image CDN, where v7 resized VTEX catalog and Shopify images on their own hosts",
    });
  }
}

const PROVIDER = "<ImageUrlProvider value={imageUrl}>{children}</ImageUrlProvider>";

/** The edit that puts `ImageUrlProvider` in one `createDecoRouter({ … })` call's `Wrap`, or undefined. */
function wrapEdit(source: ts.SourceFile, call: ts.CallExpression): Edit | undefined {
  const [options] = call.arguments;
  if (!options || !ts.isObjectLiteralExpression(options) || call.arguments.length !== 1)
    return undefined;
  const wrap = options.properties.find(
    (p) => p.name && ts.isIdentifier(p.name) && p.name.text === "Wrap",
  );
  if (wrap) {
    // An inline Wrap that renders `{children}` once: wrap that.
    if (!ts.isPropertyAssignment(wrap) || !ts.isArrowFunction(wrap.initializer)) return undefined;
    const slots: ts.JsxExpression[] = [];
    const find = (node: ts.Node) => {
      if (
        ts.isJsxExpression(node) &&
        node.expression &&
        ts.isIdentifier(node.expression) &&
        node.expression.text === "children"
      ) {
        slots.push(node);
      }
      ts.forEachChild(node, find);
    };
    find(wrap.initializer.body);
    if (slots.length !== 1) return undefined;
    return { start: slots[0].getStart(source), end: slots[0].getEnd(), text: PROVIDER };
  }
  const property = `Wrap: ({ children }) => ${PROVIDER}`;
  const last = options.properties.at(-1);
  if (!last) {
    return { start: options.getStart(source), end: options.getEnd(), text: `{ ${property} }` };
  }
  const text = source.getFullText();
  const sameLine =
    source.getLineAndCharacterOfPosition(options.getStart(source)).line ===
    source.getLineAndCharacterOfPosition(last.getEnd()).line;
  const indent = sameLine
    ? ""
    : (/^[ \t]*/.exec(text.slice(text.lastIndexOf("\n", last.getStart(source)) + 1))?.[0] ?? "");
  if (options.properties.hasTrailingComma) {
    const comma = text.indexOf(",", last.getEnd());
    return sameLine
      ? { start: comma + 1, end: comma + 1, text: ` ${property},` }
      : { start: comma + 1, end: comma + 1, text: `\n${indent}${property},` };
  }
  return sameLine
    ? { start: last.getEnd(), end: last.getEnd(), text: `, ${property}` }
    : { start: last.getEnd(), end: last.getEnd(), text: `,\n${indent}${property},` };
}
