import type { DeferredSection, ResolvedSection } from "@decocms/blocks/cms";
import { isDevMode } from "@decocms/blocks/sdk/env";
import type { Device } from "@decocms/blocks/sdk/useDevice";
import { DecoPageRenderer } from "../hooks/DecoPageRenderer";
import { deferredSectionLoader } from "../sdk/deferredSectionLoader";
import type { CmsNotFoundData } from "./cmsRoute";

/**
 * Default CMS page component. Renders all resolved sections.
 * Sites can use this directly or build their own.
 */
export function CmsPage({
  sections,
  deferredSections,
  deferredPromises,
  pagePath,
  pageUrl,
  device,
}: {
  sections: ResolvedSection[];
  deferredSections?: DeferredSection[];
  deferredPromises?: Record<string, Promise<ResolvedSection | null>>;
  pagePath?: string;
  pageUrl?: string;
  /** Server-resolved device from the page loader — keeps useDevice() hydration-stable. */
  device?: Device;
}) {
  return (
    <div>
      <DecoPageRenderer
        sections={sections}
        deferredSections={deferredSections}
        deferredPromises={deferredPromises}
        pagePath={pagePath}
        pageUrl={pageUrl}
        device={device}
        loadDeferredSectionFn={deferredSectionLoader}
      />
    </div>
  );
}

/**
 * Default "page not found" message. Neutral on purpose: inline styles (a
 * library's Tailwind classes are never generated by the site's build) that
 * inherit the site's font and colors. The developer hint shows in dev only.
 */
export function NotFoundPage() {
  return (
    <main
      style={{
        minHeight: "50vh",
        display: "flex",
        flexDirection: "column",
        alignItems: "center",
        justifyContent: "center",
        gap: "1rem",
        padding: "4rem 1rem",
        textAlign: "center",
      }}
    >
      <p style={{ margin: 0, fontSize: "4rem", fontWeight: 700, lineHeight: 1, opacity: 0.2 }}>
        404
      </p>
      <h1 style={{ margin: 0, fontSize: "1.75rem", fontWeight: 600 }}>Page not found</h1>
      <p style={{ margin: 0, maxWidth: "32rem", opacity: 0.7 }}>
        The page you are looking for does not exist or has moved.
      </p>
      {isDevMode() && (
        <p style={{ margin: 0, fontSize: "0.875rem", opacity: 0.5 }}>
          Dev: no CMS page block matches this URL. Create a page at /404 in the CMS to brand this
          page.
        </p>
      )}
      <a
        href="/"
        style={{
          marginTop: "0.5rem",
          padding: "0.625rem 1.5rem",
          border: "1px solid currentColor",
          borderRadius: "999px",
          color: "inherit",
          textDecoration: "none",
          fontWeight: 600,
        }}
      >
        Go to the homepage
      </a>
    </main>
  );
}

/**
 * Default `notFoundComponent` of `cmsRouteConfig`. Renders the CMS 404 page
 * when the site has one, else {@link NotFoundPage} inside the site's chrome
 * (Header before, Footer after). `data` is what the route loader passed to
 * `notFound({ data })`.
 */
export function CmsNotFoundPage({ data }: { data?: unknown }) {
  const page = data as CmsNotFoundData | undefined;
  if (!page) return <NotFoundPage />;
  const { messageAt, resolvedSections, ...rest } = page;
  if (messageAt === undefined) return <CmsPage sections={resolvedSections} {...rest} />;
  return (
    <>
      <CmsPage sections={resolvedSections.slice(0, messageAt)} {...rest} />
      <NotFoundPage />
      <CmsPage sections={resolvedSections.slice(messageAt)} {...rest} />
    </>
  );
}
